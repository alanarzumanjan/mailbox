export function getBoxStatus(box) {
  if (box.weight >= box.max) return "full";
  if (box.weight >= box.max * 0.75) return "warning";
  return "normal";
}

export function getBoxPercent(box) {
  return Math.min(100, Math.round((box.weight / box.max) * 100));
}
